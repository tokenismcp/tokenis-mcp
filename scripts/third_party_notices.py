"""Generate THIRD-PARTY-NOTICES.md for the Rust code statically linked into
the Python wheel (crates/tokenis-py) and the npm package's WebAssembly
(crates/tokenis-wasm).

Dual-licensed "MIT OR Apache-2.0" crates are used under Apache-2.0, whose
text ships as this repository's LICENSE; any NOTICE file such a crate has is
reproduced. Crates without an Apache-2.0 option (MIT, BSD-3-Clause,
Unicode-3.0) get their full license text, copyright lines included.

    python scripts/third_party_notices.py          # rewrite the file
    python scripts/third_party_notices.py --check  # CI: fail if stale
"""
from __future__ import annotations

import argparse
import difflib
import glob
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Tuple

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
TREES = [
    ["cargo", "tree", "-p", "tokenis-py", "-e", "normal"],
    ["cargo", "tree", "-p", "tokenis-wasm", "-e", "normal", "--target", "wasm32-unknown-unknown"],
]
LINE = re.compile(r"^(?P<name>[\w-]+) v(?P<version>\S+)(?P<rest>.*?) \| (?P<license>.+)$")


def crates() -> Dict[Tuple[str, str], str]:
    found: Dict[Tuple[str, str], str] = {}
    for cmd in TREES:
        out = subprocess.run(
            [*cmd, "--prefix", "none", "--format", "{p} | {l}"],
            cwd=ROOT, check=True, capture_output=True, text=True,
        ).stdout
        for line in out.splitlines():
            parsed = parse_line(line)
            if parsed is not None:
                found[parsed[:2]] = parsed[2]
    return found


# `cargo tree` marks a dependency it has already printed with "(*)". Cargo
# versions differ in the spacing around the marker, which once leaked into the
# license text on CI, so drop it wherever it appears.
_DEDUPE_MARK = re.compile(r"\s*\(\*\)")


def parse_line(line: str) -> "Tuple[str, str, str] | None":
    """(name, version, license) of one ``cargo tree`` line, or None for lines
    that are not third-party crates (proc-macros, our own crates)."""
    m = LINE.match(_DEDUPE_MARK.sub("", line))
    if not m or "(proc-macro)" in m["rest"] or m["name"].startswith("tokenis-"):
        return None
    return m["name"], m["version"], m["license"].strip()


def source_dir(name: str, version: str) -> Path:
    home = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo"))
    hits = glob.glob(str(home / "registry" / "src" / "*" / f"{name}-{version}"))
    if not hits:
        sys.exit(f"source for {name} {version} not found; run `cargo fetch` first")
    return Path(hits[0])


def license_text(src: Path, stems: List[str]) -> str:
    for path in sorted(src.iterdir()):
        upper = path.name.upper()
        if path.is_file() and any(upper.startswith(stem) for stem in stems):
            return path.read_text(encoding="utf-8", errors="replace").strip()
    sys.exit(f"no license file matching {stems} in {src}")


def render() -> str:
    parts = [
        "# Third-party notices\n",
        (
            "The Tokenis Python wheel and npm package contain compiled Rust code from the "
            "crates below. This file is generated by `scripts/third_party_notices.py`; do "
            "not edit it by hand.\n"
        ),
    ]
    apache, other = [], []
    for (name, version), lic in sorted(crates().items()):
        # "A AND B" obliges both texts; only a pure "... OR Apache-2.0" choice
        # is covered by our own LICENSE.
        uses_apache = "Apache-2.0" in lic and " AND " not in lic
        (apache if uses_apache else other).append((name, version, lic))

    parts.append("## Used under Apache-2.0\n")
    parts.append(
        "These crates are dual-licensed; Tokenis uses them under the Apache License "
        "2.0, whose full text is in `LICENSE`.\n"
    )
    for name, version, lic in apache:
        parts.append(f"- `{name}` {version} ({lic})")
        src = source_dir(name, version)
        notice = next((p for p in src.iterdir() if p.name.upper().startswith("NOTICE")), None)
        if notice is not None:
            parts.append(f"\n  NOTICE:\n\n  ```\n{notice.read_text().strip()}\n  ```")
    parts.append("")

    parts.append("## Other licenses\n")
    for name, version, lic in other:
        stems = ["LICENSE-UNICODE"] if "Unicode-3.0" in lic else (
            ["LICENSE-MIT", "LICENSE"] if lic == "MIT" else ["LICENSE"]
        )
        text = license_text(source_dir(name, version), stems)
        parts.append(f"### `{name}` {version} ({lic})\n\n```\n{text}\n```\n")
    return "\n".join(parts).rstrip() + "\n"


def annotate(message: str) -> None:
    """A GitHub Actions error annotation: shown on the run page even to people
    who cannot open the job log."""
    escaped = message.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
    print(f"::error title=Third-party notices::{escaped}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    try:
        text = render()
    except subprocess.CalledProcessError as exc:
        annotate(f"{' '.join(exc.cmd)} failed ({exc.returncode}): {(exc.stderr or '')[-600:]}")
        raise
    except SystemExit as exc:
        if isinstance(exc.code, str):
            annotate(exc.code)
        raise
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            diff = list(difflib.unified_diff(current.splitlines(), text.splitlines(), "committed", "generated",
                                             lineterm="", n=0))
            print("THIRD-PARTY-NOTICES.md is stale: run scripts/third_party_notices.py")
            annotate("THIRD-PARTY-NOTICES.md is stale; first differences:\n" + "\n".join(diff[:25])[:1500])
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
